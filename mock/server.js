function messageToEvents(msg) {
  const events = [];
  events.push({ choices: [{ index: 0, delta: { role: 'assistant' }, finish_reason: null }] });

  if (msg.content) {
    const pieces = [];
    for (let i = 0; i < msg.content.length; i += 14) pieces.push(msg.content.slice(i, i + 14));
    for (const p of pieces) events.push({ choices: [{ index: 0, delta: { content: p }, finish_reason: null }] });
    events.push({ choices: [{ index: 0, delta: {}, finish_reason: 'stop' }] });
  }

  if (msg.tool_calls && msg.tool_calls.length) {
    msg.tool_calls.forEach((tc, i) => {
      events.push({
        choices: [
          {
            index: 0,
            delta: { tool_calls: [{ index: i, id: tc.id, type: 'function', function: { name: tc.function.name, arguments: '' } }] },
            finish_reason: null,
          },
        ],
      });
      const args = tc.function.arguments;
      for (let j = 0; j < args.length; j += 48) {
        events.push({
          choices: [
            { index: 0, delta: { tool_calls: [{ index: i, function: { arguments: args.slice(j, j + 48) } }] }, finish_reason: null },
          ],
        });
      }
    });
    events.push({ choices: [{ index: 0, delta: {}, finish_reason: 'tool_calls' }] });
  }

  events.push({ usage: { prompt_tokens: 1200, completion_tokens: 90, total_tokens: 1290 } });
  return events;
}

function startMockServer(port = 0) {
  const server = http.createServer((req, res) => {
    if (req.method === 'GET' && req.url === '/v1/models') {
      res.writeHead(200, { 'content-type': 'application/json' });
      res.end(JSON.stringify({ data: [{ id: 'arena-agent' }, { id: 'arena-agent-fast' }, { id: 'arena-agent-mini' }] }));
      return;
    }
    if (req.method === 'POST' && req.url === '/v1/chat/completions') {
      let body = '';
      req.on('data', (d) => (body += d));
      req.on('end', () => {
        let parsed;
        try {
          parsed = JSON.parse(body || '{}');
        } catch {
          res.writeHead(400, { 'content-type': 'application/json' });
          res.end(JSON.stringify({ error: { message: 'bad JSON' } }));
          return;
        }
        const msg = pickResponse(parsed.messages || []);
        if (!parsed.stream) {
          res.writeHead(200, { 'content-type': 'application/json' });
          res.end(
            JSON.stringify({
              id: 'mock-' + Date.now(),
              choices: [{ index: 0, message: { role: 'assistant', ...msg }, finish_reason: msg.tool_calls ? 'tool_calls' : 'stop' }],
              usage: { prompt_tokens: 1200, completion_tokens: 90, total_tokens: 1290 },
            })
          );
          return;
        }
        res.writeHead(200, { 'content-type': 'text/event-stream', 'cache-control': 'no-cache' });
        const events = messageToEvents(msg);
        let i = 0;
        const timer = setInterval(() => {
          if (i >= events.length) {
            res.write('data: [DONE]\n\n');
            clearInterval(timer);
            res.end();
            return;
          }
          res.write(`data: ${JSON.stringify(events[i++])}\n\n`);
        }, 8);
      });
      return;
    }
    res.writeHead(404, { 'content-type': 'application/json' });
    res.end(JSON.stringify({ error: { message: 'not found' } }));
  });

  return new Promise((resolve, reject) => {
    server.on('error', reject);
    server.listen(port, '127.0.0.1', () => {
      resolve({
        port: server.address().port,
        url: `http://127.0.0.1:${server.address().port}`,
        close: () => new Promise((r) => server.close(r)),
      });
    });
  });
}

module.exports = { startMockServer };

if (require.main === module) {
  const port = Number(process.argv[2] || 8420);
  startMockServer(port).then((s) => {
    console.log(`mock Arena Agent API on ${s.url}/v1`);
  });
}
