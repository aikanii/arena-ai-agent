'use strict';

/**
 * Bundled offline mock of the Arena Agent API.
 *
 * It speaks OpenAI-compatible /v1/chat/completions (streaming + non-streaming)
 * and drives a small scripted "brain" that demonstrates the full agent loop:
 * plan → create files → verify with a shell command → mark plan done → summary.
 *
 * Used by `arena --mock`, the demo script and the e2e smoke test.
 */

const http = require('http');

const AUTH_FILE = 'src/auth.js';
const AUTH_TEST_CMD = `node -e "const a=require('./src/auth'); const t=a.register('kai','s3cret'); const ok=a.verify(t); console.log('auth check:', ok ? 'PASS' : 'FAIL');"`;

const AUTH_MODULE = `'use strict';

const crypto = require('crypto');

// Minimal in-memory auth module generated by Arena Agent (mock demo).
const users = new Map();   // username -> { salt, hash }
const tokens = new Map();  // token -> username

function hash(password, salt) {
  return crypto.scryptSync(password, salt, 32).toString('hex');
}

function register(username, password) {
  if (!username || !password) throw new Error('username and password are required');
  if (users.has(username)) throw new Error('user already exists: ' + username);
  const salt = crypto.randomBytes(16).toString('hex');
  users.set(username, { salt, hash: hash(password, salt) });
  return issueToken(username);
}

function login(username, password) {
  const u = users.get(username);
  if (!u) return null;
  if (hash(password, u.salt) !== u.hash) return null;
  return issueToken(username);
}

function issueToken(username) {
  const token = crypto.randomBytes(24).toString('base64url');
  tokens.set(token, username);
  return token;
}

function verify(token) {
  return tokens.has(token) ? { username: tokens.get(token) } : null;
}

function logout(token) {
  return tokens.delete(token);
}

module.exports = { register, login, verify, logout };
`;

function taskEcho(messages) {
  const lastUser = [...messages].reverse().find((m) => m.role === 'user' && typeof m.content === 'string');
  return lastUser ? String(lastUser.content).slice(0, 120).replace(/\n/g, ' ') : '(no task)';
}

function pickResponse(messages) {
  const step = messages.filter((m) => m.role === 'tool').length;
  const task = taskEcho(messages);

  switch (step) {
    case 0:
      return {
        tool_calls: [
          {
            id: 'mock_call_plan',
            type: 'function',
            function: {
              name: 'update_plan',
              arguments: JSON.stringify({
                todos: [
                  { content: `Understand task: ${task}`, status: 'done' },
                  { content: 'Implement auth module (src/auth.js)', status: 'in_progress' },
                  { content: 'Verify with a smoke test', status: 'pending' },
                ],
              }),
            },
          },
        ],
      };
    case 1:
      return {
        tool_calls: [
          {
            id: 'mock_call_write',
            type: 'function',
            function: {
              name: 'write_file',
              arguments: JSON.stringify({ path: AUTH_FILE, content: AUTH_MODULE }),
            },
          },
        ],
      };
    case 2:
      return {
        tool_calls: [
          {
            id: 'mock_call_run',
            type: 'function',
            function: {
              name: 'run_command',
              arguments: JSON.stringify({ command: AUTH_TEST_CMD, description: 'smoke-test the auth module' }),
            },
          },
        ],
      };
    case 3:
      return {
        tool_calls: [
          {
            id: 'mock_call_plan2',
            type: 'function',
            function: {
              name: 'update_plan',
              arguments: JSON.stringify({
                todos: [
                  { content: `Understand task: ${task}`, status: 'done' },
                  { content: 'Implement auth module (src/auth.js)', status: 'done' },
                  { content: 'Verify with a smoke test', status: 'done' },
                ],
              }),
            },
          },
        ],
      };
    default:
      return {
        content:
          `Done. I added a small authentication module for the task: "${task}".\n\n` +
          'What changed:\n' +
          `- Created ${AUTH_FILE} with register/login/verify/logout backed by crypto.scrypt password hashing and opaque session tokens.\n\n` +
          'Verification:\n' +
          '- Ran a smoke test that registers a user, verifies the issued token, and printed `auth check: PASS`.\n\n' +
          'Next steps you may want: wire the module into your HTTP routes, add persistent storage, and add real tests. (Note: this reply came from the bundled offline mock — point ARENA_BASE_URL/Arena_API_KEY at the real Arena Agent API for full intelligence.)',
      };
  }
}

